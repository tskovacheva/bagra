/**
 * A counted noun that agrees with its number.
 *
 * Bulgarian needs two forms for masculine nouns after a numeral — one plat,
 * two plata — and the counted form is not the plural: "два плата", never "два
 * платове". Written out as "{n} записани платове", a warning that is supposed
 * to be taken seriously reads as though nobody proofread it.
 *
 * Both languages take the same shape: `one` when the count is exactly one,
 * `many` otherwise.
 */
export function plural(n, one, many) {
  return `${n} ${n === 1 ? one : many}`;
}

export function t(key, params = null) {
  let out = (DICT[lang] && DICT[lang][key]) || DICT.bg[key] || key;
  if (params) for (const [k, v] of Object.entries(params)) {
    out = out.replaceAll('{' + k + '}', v);
  }
  return out;
}
